-- ============================================================
-- QUERY OTIMIZADA DE PROPOSTAS
-- ============================================================
-- MELHORIAS APLICADAS:
-- 1. Filtros de status aplicados dentro das CTEs
-- 2. CTE para reservas aprovadas
-- 3. Uso de NOT MATERIALIZED onde apropriado
-- 4. Simplificação de LATERAL JOINs
-- 5. Remoção de processamentos desnecessários
-- ============================================================

-- BEGIN;
-- DROP VIEW IF EXISTS PROPOSTAS;
